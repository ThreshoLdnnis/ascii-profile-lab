"""Generic command-line orchestration, kept separate from the portrait renderer."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import urllib.error
import urllib.parse

from PIL import Image

from fetch_stats import write_json_atomic


def build_readme(config: dict, stats: dict, assets: Path, root: Path) -> str:
    def asset(name: str) -> str:
        revision = hashlib.sha256((assets / name).read_bytes()).hexdigest()[:12]
        if stats.get("is_demo"):
            return f"./{name}?v={revision}"
        relative = (assets.relative_to(root) / name).as_posix()
        branch = urllib.parse.quote(config["branch"], safe="")
        return f'https://raw.githubusercontent.com/{config["repository"]}/{branch}/{relative}?v={revision}'

    from html import escape
    alt = escape(f'{config["name"]}: ASCII portrait and GitHub profile. '
                 + ("All numbers are fictional demo data." if stats.get("is_demo") else "Public GitHub data."), quote=True)
    lines = [
        '<!-- Generated by ASCII Profile Lab. Personalize profile.json. -->',
        '<picture>',
        f'  <source media="(max-width: 640px) and (prefers-color-scheme: dark)" srcset="{asset("profile-mobile-dark.svg")}">',
        f'  <source media="(max-width: 640px)" srcset="{asset("profile-mobile-light.svg")}">',
        f'  <source media="(prefers-color-scheme: dark)" srcset="{asset("profile-dark.svg")}">',
        f'  <img src="{asset("profile-light.svg")}" alt="{alt}" width="1120">',
        '</picture>', '',
    ]
    if stats.get("is_demo"):
        lines += ['> Offline demo: the robot is procedural artwork and all statistics are fictional sample values.', '']
    if config.get("introduction"):
        lines += [str(config["introduction"]), '']
    if config.get("projects"):
        lines += ['### Selected projects', '']
        for project in config["projects"]:
            name = str(project["name"])
            url = project.get("url", "")
            if url:
                if urllib.parse.urlparse(url).scheme not in {"http", "https"}:
                    raise ValueError("Project links must use http or https")
                name = f'[{name}]({url})'
            lines.append(f'- **{name}** — {project.get("description", "")}')
        lines.append('')
    lines += ['<sub>Uptime = GitHub account age. Real stats cover owned public repositories only.</sub>', '']
    return '\n'.join(lines)


def validate_readme_target(path: Path, config: dict, root: Path, demo: bool) -> None:
    if path.resolve() != (root / "README.md").resolve():
        return
    expected = f'{config["username"]}/{config["username"]}'
    if demo or config["repository"].casefold() != expected.casefold():
        raise ValueError("Root README.md is reserved for your username/username profile repository; use PROFILE_README.md here")


def main(engine) -> None:
    parser = argparse.ArgumentParser(description="Create pink-and-white ASCII GitHub profile cards.")
    parser.add_argument("--demo", action="store_true", help="Offline geometric robot and clearly marked sample numbers")
    parser.add_argument("--portrait", type=Path, help="Convert a local image instead of the public GitHub avatar")
    parser.add_argument("--offline", action="store_true", help="Use a cached portrait only if its source matches")
    parser.add_argument("--output-dir", type=Path, help="SVG/cache directory; defaults to assets or examples in demo mode")
    parser.add_argument("--readme", type=Path, help="Generated README path; default PROFILE_README.md (or examples/PROFILE_README.md for demo)")
    args = parser.parse_args()
    root = engine.ROOT
    if args.demo and args.portrait:
        raise ValueError("Choose --demo or --portrait, not both")
    assets = args.output_dir.resolve() if args.output_dir else root / ("examples" if args.demo else "assets")
    if args.demo:
        config = engine.normalize_config(dict(username="demo-user", name="Your Name", role="Developer / Explorer",
                                             focus="Offline demo / Sample values", stack="Python / SVG / GitHub Actions",
                                             now="No network or account required", tagline="From pixels to characters. Built with Python."))
        stats = json.loads((root / "examples" / "demo-stats.json").read_text(encoding="utf-8"))
    else:
        config = engine.normalize_config(json.loads((root / "profile.json").read_text(encoding="utf-8-sig")))
        stats_path = root / "assets" / "stats.json"
        if not stats_path.exists():
            raise ValueError("Run python scripts/fetch_stats.py first, or try --demo without a GitHub account")
        stats = json.loads(stats_path.read_text(encoding="utf-8"))
        if stats["login"].casefold() != config["username"].casefold():
            raise ValueError("Statistics belong to a different account. Run fetch_stats.py again.")
    target = args.readme.resolve() if args.readme else (assets if args.demo else root) / "PROFILE_README.md"
    validate_readme_target(target, config, root, args.demo)
    assets.mkdir(parents=True, exist_ok=True)
    cache = assets / "ascii-portrait.json"
    local_image = args.portrait
    if not local_image and config.get("portrait_path"):
        local_image = (root / config["portrait_path"]).resolve()
        if not local_image.is_relative_to(root):
            raise ValueError("portrait_path in profile.json must stay inside the repository")
    payload = None
    if args.demo:
        source = {"kind": "demo", "id": "geometric-robot-v1"}
    elif local_image:
        payload = local_image.read_bytes()
        source = {"kind": "local", "username": config["username"].casefold(), "sha256": hashlib.sha256(payload).hexdigest()}
    else:
        source = {"kind": "github", "username": config["username"].casefold(), "url": stats["avatar_url"]}
        if args.offline and cache.exists():
            previous_source = json.loads(cache.read_text(encoding="utf-8")).get("source", {})
            if previous_source.get("kind") == "local" and previous_source.get("username") == config["username"].casefold():
                source = previous_source
    portrait = None
    if args.demo:
        portrait = engine.demo_portrait()
    elif not args.offline:
        try:
            if payload is None:
                payload = engine.download_avatar(stats["avatar_url"])
            with Image.open(io.BytesIO(payload)) as image:
                portrait = engine.portrait_from_image(image)
        except (OSError, ValueError, urllib.error.URLError):
            if not cache.exists():
                raise
            # Source verification below prevents reusing another person's avatar.
            print("Image refresh unavailable; checking whether the existing cache matches this source.")
    if portrait is None:
        if not cache.exists():
            raise ValueError("No matching portrait cache. Run once without --offline.")
        portrait = json.loads(cache.read_text(encoding="utf-8"))
    else:
        portrait["source"] = source
    engine.validate_portrait(portrait, source)
    engine.ASSETS = assets
    write_json_atomic(cache, portrait)
    for mode in engine.THEMES:
        for mobile in (False, True):
            name = f'profile-{"mobile-" if mobile else ""}{mode}.svg'
            (assets / name).write_text(engine.render(config, stats, portrait, mode, mobile), encoding="utf-8")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build_readme(config, stats, assets, root), encoding="utf-8")
    print(f"Generated four SVG cards in {assets} and {target}.")
